from fastapi import FastAPI, UploadFile, File
from fastapi.responses import JSONResponse
import os

app = FastAPI(title="KaatibDocsPro PDF to Word Service")

@app.get("/health")
def health():
    return {"status": "ok", "service": "pdf2word"}

@app.post("/convert")
async def convert_pdf_to_word(file: UploadFile = File(...)):
    temp_dir = "/tmp/kaatibdocspro"
    os.makedirs(temp_dir, exist_ok=True)

    pdf_path = os.path.join(temp_dir, file.filename)
    output_name = os.path.splitext(file.filename)[0] + ".docx"
    output_path = os.path.join(temp_dir, output_name)

    content = await file.read()
    with open(pdf_path, "wb") as f:
        f.write(content)

    with open(output_path, "wb") as out:
        out.write(b"sample-docx-content-placeholder")

    return JSONResponse(
        {
            "status": "completed",
            "outputFile": output_path,
            "message": "Sample conversion result generated by the backend placeholder service."
        }
    )
